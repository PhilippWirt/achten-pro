#!/usr/bin/env python3
from __future__ import annotations

import hashlib
import json
import re
import subprocess
import tempfile
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = [
    ROOT / 'index.html',
    ROOT / 'en/index.html',
    ROOT / 'playfight/index.html',
    ROOT / 'playfight/de/index.html',
]

class AuditParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.tags=[]
        self.ids=[]
        self.links=[]
        self.images=[]
        self.sections=[]
        self.scripts=[]
        self._script=None
        self.lang=None
        self.canonical=[]
        self.alternates={}
        self.title=''
        self._in_title=False
    def handle_starttag(self, tag, attrs):
        data=dict(attrs)
        self.tags.append(tag)
        if tag == 'html': self.lang=data.get('lang')
        if data.get('id'): self.ids.append(data['id'])
        if tag == 'section': self.sections.append(data.get('id',''))
        if tag == 'a' and data.get('href'): self.links.append(data['href'])
        if tag == 'img' and data.get('src'): self.images.append(data['src'])
        if tag == 'link' and data.get('rel') == 'canonical': self.canonical.append(data.get('href'))
        if tag == 'link' and data.get('rel') == 'alternate': self.alternates[data.get('hreflang')]=data.get('href')
        if tag == 'script': self._script=[]
        if tag == 'title': self._in_title=True
    def handle_data(self, data):
        if self._script is not None: self._script.append(data)
        if self._in_title: self.title += data
    def handle_endtag(self, tag):
        if tag == 'script' and self._script is not None:
            self.scripts.append(''.join(self._script)); self._script=None
        if tag == 'title': self._in_title=False

def digest_outputs():
    return {str(path.relative_to(ROOT)):hashlib.sha256(path.read_bytes()).hexdigest() for path in OUTPUTS}

def local_target(url: str, page: Path):
    parsed=urlsplit(url)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return None
    if parsed.path == '/': return ROOT/'index.html'
    candidate=(ROOT/parsed.path.lstrip('/')) if parsed.path.startswith('/') else (page.parent/parsed.path)
    if parsed.path.endswith('/'): candidate=candidate/'index.html'
    return candidate

errors=[]
subprocess.run(['python3','build.py'],cwd=ROOT,check=True,capture_output=True,text=True)
first=digest_outputs()
subprocess.run(['python3','build.py'],cwd=ROOT,check=True,capture_output=True,text=True)
second=digest_outputs()
if first != second: errors.append('double build is not reproducible')

parsed={}
for path in OUTPUTS:
    if not path.is_file():
        errors.append(f'missing output {path.relative_to(ROOT)}'); continue
    text=path.read_text()
    parser=AuditParser(); parser.feed(text); parsed[path]=parser
    duplicates=[item for item,count in Counter(parser.ids).items() if count>1]
    if duplicates: errors.append(f'{path.relative_to(ROOT)} duplicate ids: {duplicates}')
    if 'Newsreader' not in text or 'IBM Plex Sans' not in text:
        errors.append(f'{path.relative_to(ROOT)} missing editorial font pair')
    if 'Instrument Serif' in text or 'Manrope' in text:
        errors.append(f'{path.relative_to(ROOT)} still contains old generic font pair')
    if 'document.cookie' in text or 'window.location.href' in text:
        errors.append(f'{path.relative_to(ROOT)} contains automatic/cookie language logic')
    if 'Generated by build.py' not in text:
        errors.append(f'{path.relative_to(ROOT)} missing generated marker')
    for url in parser.links + parser.images:
        target=local_target(url, path)
        if target is not None and not target.exists():
            errors.append(f'{path.relative_to(ROOT)} missing local target {url} -> {target.relative_to(ROOT)}')
    for index,script in enumerate(parser.scripts):
        if not script.strip(): continue
        with tempfile.NamedTemporaryFile('w',suffix='.js',delete=False) as handle:
            handle.write(script); temp=Path(handle.name)
        result=subprocess.run(['node','--check',str(temp)],capture_output=True,text=True)
        temp.unlink(missing_ok=True)
        if result.returncode: errors.append(f'{path.relative_to(ROOT)} script {index}: {result.stderr.strip()}')

expected={
    ROOT/'index.html':('de','https://achten.pro/','/','/en/'),
    ROOT/'en/index.html':('en','https://achten.pro/en/','/','/en/'),
    ROOT/'playfight/index.html':('en','https://achten.pro/playfight/','/playfight/de/','/playfight/'),
    ROOT/'playfight/de/index.html':('de','https://achten.pro/playfight/de/','/playfight/de/','/playfight/'),
}
for path,(lang,canonical,de_url,en_url) in expected.items():
    parser=parsed.get(path)
    if not parser: continue
    if parser.lang != lang: errors.append(f'{path.relative_to(ROOT)} lang={parser.lang}, expected {lang}')
    if parser.canonical != [canonical]: errors.append(f'{path.relative_to(ROOT)} canonical={parser.canonical}')
    if parser.alternates.get('de') != 'https://achten.pro'+de_url: errors.append(f'{path.relative_to(ROOT)} wrong de alternate')
    if parser.alternates.get('en') != 'https://achten.pro'+en_url: errors.append(f'{path.relative_to(ROOT)} wrong en alternate')
    if de_url not in parser.links or en_url not in parser.links: errors.append(f'{path.relative_to(ROOT)} language links missing')

for left,right in [(ROOT/'index.html',ROOT/'en/index.html'),(ROOT/'playfight/index.html',ROOT/'playfight/de/index.html')]:
    if parsed[left].tags != parsed[right].tags: errors.append(f'tag structure differs: {left.relative_to(ROOT)} vs {right.relative_to(ROOT)}')
    if parsed[left].sections != parsed[right].sections: errors.append(f'section ids differ: {left.relative_to(ROOT)} vs {right.relative_to(ROOT)}')
    if parsed[left].ids != parsed[right].ids: errors.append(f'id sequence differs: {left.relative_to(ROOT)} vs {right.relative_to(ROOT)}')

if (ROOT/'playfight/en').exists(): errors.append('obsolete playfight/en still exists')
for path in (ROOT/'playfight/index.html',ROOT/'playfight/de/index.html'):
    text=path.read_text()
    experience=text.split('<section id="experience"',1)[1].split('</section>',1)[0]
    contact=text.split('<section id="contact"',1)[1].split('</section>',1)[0]
    if 'experience-crosslink' not in experience or 'Personal Training' not in experience:
        errors.append(f'{path.relative_to(ROOT)} Personal Training missing under Experience')
    if 'Personal Training' in contact:
        errors.append(f'{path.relative_to(ROOT)} Personal Training still appears under Contact')
    desktop_nav=text.split('<nav class="nav-links"',1)[1].split('</nav>',1)[0]
    personal_href='/en/' if path == ROOT/'playfight/index.html' else '/'
    expected_nav=['#offer',personal_href,'#why','#experience','#contact']
    positions=[desktop_nav.find(f'href="{href}"') for href in expected_nav]
    if -1 in positions or positions != sorted(positions) or 'nav-group' in desktop_nav or 'nav-sub' in desktop_nav:
        errors.append(f'{path.relative_to(ROOT)} desktop navigation is not flat or has the wrong order')

# Targeted language residue checks for customer-visible copy.
if re.search(r'\b(Angebot|Warum|Erfahrung|Anfrage senden|Echter Kontakt)\b', (ROOT/'playfight/index.html').read_text()):
    errors.append('playfight English output contains German customer copy')
if re.search(r'\b(Get the guide|Why Playfight|Science you can feel|Send inquiry|Real contact)\b', (ROOT/'playfight/de/index.html').read_text()):
    errors.append('playfight German output contains English customer copy')

result={'ok':not errors,'errors':errors,'hashes':second,'pages':{str(p.relative_to(ROOT)):{'lang':parsed[p].lang,'sections':parsed[p].sections,'ids':len(parsed[p].ids),'links':len(parsed[p].links)} for p in OUTPUTS}}
print(json.dumps(result,ensure_ascii=False,indent=2))
raise SystemExit(0 if not errors else 1)
